#!/usr/bin/env node
// gen-build-info.js — bakes the bundle's build time into src/build-info.ts.
//
// The UI's answer to __DATE__/__TIME__. Angular has no built-in equivalent:
// angular.json's `define` takes static strings, so a timestamp has to be written
// by something that runs at build time. This is that something.
//
// The file is COMMITTED rather than gitignored, and deliberately: a bare
// `tsc --noEmit` has to compile without running npm scripts first, and a generated
// import that isn't there fails the typecheck on a fresh clone. It churns on every
// build, which is the same deal firmware/data/* already makes.
//
// Run automatically by prebuild/prestart (npm's own hooks) — see package.json.

'use strict';
const fs = require('fs');
const path = require('path');

const out = path.join(__dirname, 'src', 'build-info.ts');
const stamp = Date.now();

fs.writeFileSync(out, `// GENERATED by gen-build-info.js — do not edit.
// Rewritten on every build; the value is Date.now() at build time.
export const BUILD_TIME_MS = ${stamp};
`);

console.log(`[build-info] ${new Date(stamp).toISOString()} → src/build-info.ts`);
